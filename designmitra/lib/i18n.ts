// Map other languages to Hindi for fallback representation if translation is missing, otherwise return English
const languageFallback: Record<string, string> = {
  te: "hi",
  mr: "hi",
  ta: "hi",
  gu: "hi",
  kn: "hi",
  ml: "hi",
  pa: "hi",
};

export function useTranslation() {
  const { user } = useApp();
  const lang = user?.language || "en";

  return {
    t: (key: string): string => {
      // Direct lookup
      if (translations[lang] && translations[lang][key]) {
        return translations[lang][key];
      }
      // Fallback language lookup
      const fallbackLang = languageFallback[lang];
      if (fallbackLang && translations[fallbackLang] && translations[fallbackLang][key]) {
        return translations[fallbackLang][key];
      }
      return key;
    },
    lang,
  };
}
